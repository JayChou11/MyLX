CREATE TABLE `sys_score_warning_record` (
                               `warning_id` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '记录ID',
                               `score_id` bigint(20) NOT NULL COMMENT '成绩ID',
                               `student_id` bigint(20) NOT NULL COMMENT '学生ID',
                               `exam_id` bigint(20) NOT NULL COMMENT '考试批次ID',
                               `warning_type` varchar(32) NOT NULL COMMENT '预警类型',
                               `warning_level` char(1) NOT NULL COMMENT '预警等级：1低 2中 3高',
                               `warning_item` varchar(32) NOT NULL DEFAULT '' COMMENT '预警项目',
                               `warning_reason` varchar(500) DEFAULT NULL COMMENT '预警原因',
                               `warning_status` char(1) NOT NULL DEFAULT '0' COMMENT '状态：0待处理 1已处理 2已忽略',
                               `handle_result` varchar(500) DEFAULT NULL COMMENT '处理结果',
                               `handle_time` datetime DEFAULT NULL COMMENT '处理时间',
                               `handler_id` bigint(20) DEFAULT NULL COMMENT '处理人ID',
                                `handler_name` varchar(64) DEFAULT NULL COMMENT '处理人姓名',
                               `create_by` varchar(64) DEFAULT '' COMMENT '创建者',
                               `create_time` datetime DEFAULT NULL COMMENT '创建时间',
                               `update_by` varchar(64) DEFAULT '' COMMENT '更新者',
                               `update_time` datetime DEFAULT NULL COMMENT '更新时间',
                               `remark` varchar(500) DEFAULT NULL COMMENT '备注',
                               PRIMARY KEY (`warning_id`),
                               KEY `sys_score_warning_record_exam_id` (`exam_id`),
                               KEY `sys_score_warning_record_warning_status` (`warning_status`),
                               KEY `sys_score_warning_record_score_id` (`score_id`),
                               KEY `idx_score_warning_student_id` (`student_id`),
                               UNIQUE KEY `uk_sys_score_warning_record_scoreId_warningType_subjectName` (`score_id`, `warning_type`, `warning_item`)
) ENGINE=InnoDB AUTO_INCREMENT=106 DEFAULT CHARSET=utf8mb4 COMMENT='学生成绩预警记录表';